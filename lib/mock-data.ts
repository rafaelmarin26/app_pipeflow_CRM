/**
 * Typed fixtures for phases 1 and 2 — PLAN.md M2.
 *
 * The rule that makes this disposable instead of throwaway: every row has the
 * exact shape of its table in types/database.ts. Same field names, same enums,
 * cents as integers, timestamps as ISO strings. Swapping a screen over to
 * Supabase in phase 3 is one query in one Server Component, not a refactor.
 *
 * Components must NEVER import this file. Only the Server Component of a page
 * reads it and passes data down as props.
 */

/** Deterministic stand-in for a Postgres uuid. Keeps the fixtures diff-friendly. */
function id(kind: number, n: number): string {
  return `${String(kind).padStart(8, "0")}-0000-4000-8000-${String(n).padStart(
    12,
    "0",
  )}`;
}

